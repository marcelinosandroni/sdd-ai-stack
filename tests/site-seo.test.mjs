import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { DEFAULT_THEME, THEME_DIR } from "../lib/constants.mjs";

const REPO_ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = path.join(REPO_ROOT, "site");
const SITE_APP = path.join(SITE, "src", "app");
const SITE_PUBLIC = path.join(SITE, "public");
const CONTENT = path.join(SITE, "src", "content.ts");
const THEME = path.join(REPO_ROOT, THEME_DIR, DEFAULT_THEME, "tokens.css");

/**
 * What a shared link shows.
 *
 * The site had an `openGraph` block with no image in it, no sitemap, no robots, no
 * icons, no manifest and no structured data. Which means the link posted on LinkedIn
 * and sent on WhatsApp rendered as a bare title on an empty rectangle — and that link
 * is the entire distribution channel.
 *
 * The card was then generated by `ImageResponse`, which turned out to be worse: under
 * `output: "export"` it emits an extensionless file, and the static host serving it
 * returns **no Content-Type at all**. Verified, not assumed. A crawler is entitled to
 * refuse an image with no declared type, and the symptom is the blank card this exists
 * to prevent. So it is a committed `.png` with an extension every host agrees on.
 *
 * A screenshot proves the card looks right today. These prove it is still there after
 * the next six edits.
 */

function read(file) {
  return fs.readFileSync(file, "utf8");
}

/** A PNG's IHDR width and height live at bytes 16 and 20. */
function pngSize(file) {
  const png = fs.readFileSync(file);
  assert.equal(png.readUInt32BE(0), 0x89504e47, `${path.basename(file)} is not a PNG`);
  return { width: png.readUInt32BE(16), height: png.readUInt32BE(20) };
}

test("the share card is a PNG with an extension, at the size platforms crop for", () => {
  for (const [file, width, height] of [
    ["opengraph-image.png", 1200, 630],
    ["icon.png", 512, 512],
    ["apple-icon.png", 180, 180],
  ]) {
    const full = path.join(SITE_PUBLIC, file);
    assert.ok(
      fs.existsSync(full),
      `site/public/${file} is missing. public/ was empty, so the site has no icon at all ` +
        `and every share renders without a card.`,
    );

    const size = pngSize(full);
    assert.equal(size.width, width, `${file} is ${size.width}px wide`);
    assert.equal(size.height, height, `${file} is ${size.height}px tall`);
  }
});

test("nothing generates the card, so no route can shadow the static file", () => {
  // Both would exist if the `ImageResponse` route were still there, and the route wins
  // on URL: the page would advertise an extensionless file that no host can type, while
  // the working `.png` sits unused next to it.
  for (const file of ["opengraph-image.tsx", "icon.tsx", "apple-icon.tsx"]) {
    assert.ok(
      !fs.existsSync(path.join(SITE_APP, file)),
      `site/src/app/${file} exists. Under output: "export" it emits an extensionless file ` +
        `that no host can type, and it shadows public/${file.replace(".tsx", ".png")}.`,
    );
  }
});

test("the card carries no version, because it is a committed file", () => {
  // The hero said `v0.2.0` while npm was at `0.6.0`. A card that repeats the version
  // would repeat that failure on somebody's timeline, where nobody can edit it, and a
  // stale version looks checked. So the version lives on the page — where a script and
  // a guard keep it honest — and not on an image that cannot be regenerated per build.
  const seo = read(path.join(SITE_APP, "seo.ts"));

  assert.doesNotMatch(
    seo,
    /VERSION[^;]*opengraph-image|opengraph-image[^;]*VERSION/,
    "the card's URL is built from the version",
  );
  assert.match(read(path.join(SITE, "src", "content.ts")), /export const VERSION = "[^"]+";/);
});

test("the card takes its colours from the theme, checked by a test", () => {
  // The card cannot read the theme file: Vercel builds this site with `site/` as its
  // root, so that file is not in the build context. Reading it would work locally and
  // fall back in production — one design system in two colours, visible only on
  // somebody else's timeline. So the values live in content.ts and are tied here.
  const content = read(CONTENT);
  const theme = read(THEME);

  const tokens = {
    surfaceBase: "--color-surface-base",
    textPrimary: "--color-text-primary",
    textSecondary: "--color-text-secondary",
    textTertiary: "--color-text-muted",
    borderSubtle: "--color-border-subtle",
    primary: "--color-primary",
  };

  for (const [name, cssVariable] of Object.entries(tokens)) {
    const declared = new RegExp(`${name}:\\s*"(#[0-9A-Fa-f]{6})"`).exec(content)?.[1];
    const themed = new RegExp(`${cssVariable}:\\s*(#[0-9A-Fa-f]{6})`).exec(theme)?.[1];

    assert.ok(declared, `OG_TOKENS.${name} is missing from site/src/content.ts`);
    assert.ok(themed, `${cssVariable} is missing from the theme file`);

    assert.equal(
      declared.toLowerCase(),
      themed.toLowerCase(),
      `OG_TOKENS.${name} is ${declared} but ${cssVariable} is ${themed}. The share card ` +
        `would be a different colour than the site, and it is the one nobody can edit ` +
        `after it is posted.`,
    );
  }
});

test("the sitemap exists, and lists no fragments", () => {
  const sitemap = read(path.join(SITE_APP, "sitemap.ts"));

  assert.match(sitemap, /MetadataRoute\.Sitemap/, "no sitemap route in the app");
  assert.match(sitemap, /force-static/, "output: 'export' refuses to build a dynamic route");

  // A fragment is not a document. Listing `/#what` tells a crawler the site has five
  // pages when it has one, and search engines are explicit that fragments do not
  // belong in a sitemap.
  assert.doesNotMatch(sitemap, /path:\s*"[^"]*#/, "the sitemap lists a URL with a fragment");
});

test("robots.txt points at the sitemap, and uses the same origin", () => {
  const robots = read(path.join(SITE_APP, "robots.ts"));

  assert.match(robots, /sitemap:/, "robots.txt does not name the sitemap, so a crawler guesses");
  assert.match(
    robots,
    /SITE\.url/,
    "robots.ts hardcodes an origin. The sitemap and robots file have to agree, and two " +
      "typed copies of a hostname is how they stop agreeing.",
  );
});

test("the icons are declared in metadata and in the manifest", () => {
  const layout = read(path.join(SITE_APP, "layout.tsx"));
  const manifest = read(path.join(SITE_APP, "manifest.ts"));

  assert.match(layout, /icons:[\s\S]*OG_ICON\.url/, "no favicon in the metadata");
  assert.match(layout, /apple:[\s\S]*OG_APPLE_ICON\.url/, "no Apple touch icon");
  assert.match(manifest, /OG_ICON\.url/, "the manifest lists no icon");
  assert.match(manifest, /OG_APPLE_ICON\.url/, "the manifest lists no Apple touch icon");

  // iOS does not read /icon and will not round its corners: without apple-touch-icon a
  // shared link saved to the home screen gets the page screenshot as its icon.
  assert.ok(fs.existsSync(path.join(SITE_PUBLIC, "apple-icon.png")));
});

test("structured data describes a package, not an application", () => {
  const seo = read(path.join(SITE_APP, "seo.ts"));

  // `SoftwareApplication` implies something with a UI the user runs. This is an
  // MIT-licensed package with a repository — `SoftwareSourceCode` is the honest type,
  // and misdescribing the page is a liability rather than a bonus.
  assert.match(seo, /SoftwareSourceCode/, "the package is described as something it is not");
  assert.doesNotMatch(
    seo,
    /"@type":\s*"SoftwareApplication"/,
    "SoftwareApplication claims an application UI this package does not have",
  );

  for (const type of ["Person", "WebSite"]) {
    assert.match(seo, new RegExp(`"@type": "${type}"`), `no ${type} in the graph`);
  }

  assert.match(seo, /"@graph"/, "three loose scripts cannot reference each other; one graph can");
  assert.match(seo, /license:/, "the licence is part of what a crawler records");

  // LinkedIn is where the link gets shared from. A Person node that does not link it
  // gives the crawler nothing to connect.
  assert.match(seo, /SITE\.author\.linkedin/, "the Person node does not link LinkedIn");
});

test("the JSON-LD is in the document, and escaped", () => {
  const layout = read(path.join(SITE_APP, "layout.tsx"));

  assert.match(layout, /application\/ld\+json/, "structured data is computed but never rendered");
  // `</script>` inside JSON closes the tag early and the rest becomes page text — the
  // oldest structured-data bug there is.
  assert.match(
    layout,
    /replace\(\/<\/g, "\\\\u003c"\)/,
    "the JSON-LD is not escaped. A `<` in the payload can close the script tag early.",
  );
});

test("openGraph and twitter both carry an absolute image", () => {
  const layout = read(path.join(SITE_APP, "layout.tsx"));
  const seo = read(path.join(SITE_APP, "seo.ts"));

  assert.match(layout, /openGraph:[\s\S]*images: \[OG_IMAGE\]/, "openGraph has no image");
  assert.match(layout, /twitter:[\s\S]*images: \[TWITTER_IMAGE\]/, "twitter has no image");

  // Absolute, and with an extension. A relative URL is resolved against nothing and
  // fails silently; an extensionless one is fetched with no type. Together they are the
  // two ways a share card ends up blank with no error anywhere.
  assert.match(
    seo,
    /url: `\$\{SITE\.url\}\/opengraph-image\.png`/,
    "the card URL must be absolute AND carry a .png extension",
  );
  assert.match(seo, /url: `\$\{SITE\.url\}\/icon\.png`/, "the icon URL must be absolute");
  assert.match(seo, /url: `\$\{SITE\.url\}\/apple-icon\.png`/, "the Apple icon URL must be absolute");
});

test("the canonical origin is stated once", () => {
  // It was declared twice — as `SITE.url` in content.ts and as a local
  // `const SITE = "https://…"` in layout.tsx — which is how a canonical, a sitemap and
  // a robots file end up naming three different hosts. Every consumer reads it from
  // `content.ts` now, and this is what keeps it that way.
  const layout = read(path.join(SITE_APP, "layout.tsx"));

  assert.doesNotMatch(
    layout,
    /const\s+SITE\s*=\s*["']https?:/,
    "layout.tsx declares its own origin. Import SITE from @/content instead — the " +
      "sitemap, the robots file and the share card all read SITE.url from there, and a " +
      "second copy is how they stop agreeing.",
  );
  assert.match(layout, /new URL\(SITE\.url\)/, "metadataBase does not read the shared origin");
  assert.match(layout, /url: SITE\.url/, "openGraph.url does not read the shared origin");
});

test("search-console ownership is wired, and absent by default", () => {
  const layout = read(path.join(SITE_APP, "layout.tsx"));

  assert.match(
    layout,
    /NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION/,
    "nothing claims the property, so Google Search Console cannot verify it",
  );
  assert.match(
    layout,
    /process\.env\.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION\s*\?/,
    "the verification tag is emitted unconditionally, which puts a placeholder in the " +
      "document whenever the variable is unset. It has to disappear instead.",
  );
});

