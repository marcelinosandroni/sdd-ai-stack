import { OG_TOKENS, SITE, VERSION } from "@/content";

/**
 * Structured data, as one `@graph`.
 *
 * One script with a graph beats three scripts: a crawler reads one blob, and the
 * entities can reference each other by `@id` so the person, the site and the package
 * are known to be related rather than three unrelated things on a page.
 *
 * The types are chosen for what this actually is. `SoftwareApplication` is wrong — it
 * implies something the user installs and runs with a UI, and this is a package. It is
 * an MIT-licensed, source-available tool with a repository, an author and a licence, so
 * `SoftwareSourceCode` describes it accurately, and `WebSite` describes the page.
 *
 * Validated with Google's Rich Results Test; see the PR that introduced this for the
 * shape it accepted. Structured data that misdescribes the page is a liability, not a
 * bonus.
 */
export function structuredData() {
  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "Person",
        "@id": `${SITE.url}/#person`,
        name: SITE.author.name,
        jobTitle: SITE.author.title,
        email: `mailto:${SITE.author.email}`,
        url: SITE.resume,
        sameAs: [SITE.author.github, SITE.author.linkedin, SITE.repo],
      },
      {
        "@type": "WebSite",
        "@id": `${SITE.url}/#website`,
        url: SITE.url,
        name: SITE.name,
        description: DESCRIPTION,
        inLanguage: "en",
        publisher: { "@id": `${SITE.url}/#person` },
      },
      {
        "@type": "SoftwareSourceCode",
        "@id": `${SITE.url}/#code`,
        name: SITE.package,
        description: DESCRIPTION,
        url: SITE.url,
        codeRepository: SITE.repo,
        issueTracker: SITE.issues,
        license: "https://opensource.org/licenses/MIT",
        programmingLanguage: ["TypeScript", "CSS"],
        runtimePlatform: "Node.js",
        author: { "@id": `${SITE.url}/#person` },
        version: VERSION,
        // The install command is the one thing a reader of this data can act on, and
        // schema.org has no field for it — so it goes in the description people read
        // rather than in a field the validator ignores.
        abstract:
          "npx create-sdd-ai-stack my-app — a project ready for AI agents, built on Spec-Driven Development: SDD rules, a portable design system, and gates that fail.",
      },
    ],
  };
}

const DESCRIPTION =
  "Spec-Driven Development for AI agents: one command, one Next.js 16 template, 25 rule files and gates that cannot be bypassed. Open source, by Marcelino Sandroni Dias.";

/**
 * The share card, as a static file with an extension.
 *
 * It was generated by `ImageResponse` at build time, and that turned out to be wrong
 * for this site. `output: "export"` emits extensionless files, and a static host has
 * no way to know what `opengraph-image` is: verified, it serves the file with **no
 * Content-Type at all**. A crawler that fetches an image with no declared type is
 * entitled to refuse it — and the symptom is exactly the blank card this was built to
 * prevent.
 *
 * `og:image:type` is declared and most crawlers use it, but "most" is not the standard
 * to ship a distribution channel on. A `.png` extension is typed correctly by every
 * host, including the one that serves this.
 *
 * The consequence is that the card is a committed asset, so it must carry nothing that
 * changes: **no version**. The version lives on the page, where a script and a guard
 * keep it honest. A card that says `v0.2.0` on somebody's timeline is worse than a
 * card with no version, because it looks checked.
 *
 * Regenerate with `npm run assets:card`, which renders all three files from
 * `content.ts` in a plain Node process — no Next build, no dev server. A guard in
 * `tests/unit/share-card.test.ts` re-renders and compares byte for byte, so the card
 * cannot quietly drift away from the content it is drawn from.
 */
export const OG_IMAGE = {
  url: `${SITE.url}/opengraph-image.png`,
  width: 1200,
  height: 630,
  alt: `${SITE.name} — Spec-Driven Development for AI agents`,
};

export const TWITTER_IMAGE = OG_IMAGE.url;
export const OG_ICON = { url: `${SITE.url}/icon.png`, sizes: "512x512" };
export const OG_APPLE_ICON = { url: `${SITE.url}/apple-icon.png`, sizes: "180x180" };

export { OG_TOKENS, SITE, VERSION };
